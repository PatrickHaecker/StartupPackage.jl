end

module Helpers
global flag = false
global pending
const expansions = Ref(0)
macro counted(ex)
    expansions[] += 1
    return esc(ex)
end
macro count()
    return expansions[] += 1
end
macro sequential()
    return esc(Expr(:toplevel, :(using Main.Doubler: @twice), :(sequential() = @twice 21)))
end
macro staged()
    return esc(Expr(:toplevel, :(push!(events, :middle))))
end
macro typed()
    return esc(:(macro_typed::Int = 4))
end
macro other_flag()
    return Expr(:(=), GlobalRef(Helpers, :flag), true)
end
macro imports()
    return :(using Base: summarysize)
end
macro exports()
    return esc(:(export exported_by_macro))
end
macro precompiles()
    return :(precompile(sum, (Vector{Float64},)))
end
end

const LINE = LineNumberNode(1, :runtests)

latest(mod, name) = Base.invokelatest(getglobal, mod, name)

"Generate a module from `statements` as the package generated by `@startup` would be, without running `__init__`."
function generate(statements...)
    mod = Module(:Generated)
    Core.eval(mod, :(using Main.Helpers: @counted, @count, @sequential, @staged, @typed, @other_flag, @imports, @exports,
        @precompiles))
    state = StartupPackage.State(mod)
    # Each call is a top-level statement of the generated package, so it runs in the latest world.
    foreach(ex -> Base.invokelatest(StartupPackage.statement!, state, mod, LINE, ex), statements)
    Base.invokelatest(StartupPackage.define_init!, state, mod, LINE)
    Base.invokelatest(StartupPackage.finish!, state, mod)
    return mod, state
end

initialize(mod) = Base.invokelatest(latest(mod, :__init__))

# A stand-in for `Base.active_repl`, which Julia asks for the active module once it is defined.
