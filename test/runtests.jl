# A stand-in for the line editor of a `LineEditREPL` of Julia 1.12 and later, recording what `report` calls.
module FakeLineEdit
mutable struct MIState
    n_keys_pressed::Int
    async_channel::Channel{Function}
    calls::Vector{Symbol}
end
state(s::MIState) = s
clear_input_area(s::MIState) = push!(s.calls, :clear)
refresh_line(s::MIState) = push!(s.calls, :refresh)
end
struct EditREPL <: REPL.AbstractREPL
    mistate::FakeLineEdit.MIState
end
Base.active_module(::EditREPL) = Main
struct FakeBackend
    ast_transforms::Vector{Any}
end

@testset "StartupPackage" begin
    @testset "definitions at top level, statements in __init__" begin
        delete!(ENV, "STARTUP_PACKAGE_TEST")
        delete!(ENV, "STARTUP_PACKAGE_CLOSURE")
        mod, _ = generate(
            :(Base.@kwdef struct Point; x::Int = 1; end),
            :(Base.show(io::IO, ::Point) = print(io, "P")),
            :(@inline inlined(x) = x + 1),
            :(@enum Color red blue),
            :(const answer = 42),
            Meta.parse("\"Documented.\"\ndocumented() = 1"),
            :(ENV["STARTUP_PACKAGE_TEST"] = "ran"),
            :(foreach(name -> ENV[name] = "ran", ["STARTUP_PACKAGE_CLOSURE"])))
        @test sprint(show, latest(mod, :Point)()) == "P"
        @test latest(mod, :inlined)(1) == 2
        @test length(instances(latest(mod, :Color))) == 2
        @test latest(mod, :answer) == 42
        @test haskey(Base.Docs.meta(mod), Base.Docs.Binding(mod, :documented))
        @test !haskey(ENV, "STARTUP_PACKAGE_TEST") && !haskey(ENV, "STARTUP_PACKAGE_CLOSURE")
        initialize(mod)
        @test ENV["STARTUP_PACKAGE_TEST"] == "ran" && ENV["STARTUP_PACKAGE_CLOSURE"] == "ran"
        @test filter((:Point, :inlined, :Color, :red, :answer, :documented)) do name
            !Base.invokelatest(Base.isexported, mod, name)
        end == ()
    end

    @testset "precompile at top level" begin
        _, state = generate(
            :(precompile(sum, (Vector{Int},))),
            :(if true; Base.precompile(Tuple{typeof(prod), Vector{Int}}); end),
            :(@precompiles),
            :(for T in (Int8, Int16); precompile(sum, (Vector{T},)); end))
        @test !any(ex -> ex isa Expr && occursin("precompile", string(ex)), state.initializers)
        mod, _ = generate(
            :(const own_calls = Ref(0)),
            :(precompile(x) = (own_calls[] += 1)),
            :(precompile(:own)))
        @test latest(mod, :own_calls)[] == 0
        initialize(mod)
        @test latest(mod, :own_calls)[] == 1
        mod, _ = generate(
            :(const events = Symbol[]),
            :(let precompile = x -> push!(events, x); precompile(:let); end),
            :(for precompile in (x -> push!(events, x),); precompile(:loop); end),
            :(callback = Base.precompile),
            :(let; global callback = x -> push!(events, x); callback(:reassigned); end))
        @test isempty(latest(mod, :events))
        initialize(mod)
        @test latest(mod, :events) == [:let, :loop, :reassigned]
        _, state = generate(
            :(const alias = precompile),
            :(alias(sum, (Vector{Int8},))))
        @test !any(ex -> ex isa Expr && occursin("alias", string(ex)), state.initializers)
    end

    @testset "assignments" begin
