    @testset "background loading helpers" begin
        ready = Channel{Nothing}(1)
        StartupPackage.LOADING[] = Threads.@spawn take!(ready)
        try
            @test StartupPackage.wait_for_loading(:(f(1))) == :(f(1))
            waiting = Threads.@spawn StartupPackage.wait_for_loading(:(if true; using Printf; end))
            sleep(0.2)
            @test !istaskdone(waiting)
            put!(ready, nothing)
            @test Meta.isexpr(fetch(waiting), :if)
        finally
            StartupPackage.LOADING[] = nothing
        end
        calls = Tuple{Symbol, Symbol}[]
        atreplinit(repl -> push!(calls, (:old, repl)))
        atreplinit(repl -> push!(calls, (:first, repl)))
        atreplinit(repl -> error("broken"))
        atreplinit(repl -> push!(calls, (:last, repl)))
        io = IOBuffer()
        try
            StartupPackage.run_repl_hooks(:repl, 3, io)
        finally
            deleteat!(Base.repl_hooks, 1:4)
        end
        # Newest first, as Julia runs them, and the hook already run before loading is skipped.
        @test calls == [(:last, :repl), (:first, :repl)]
        @test String(take!(io)) == "broken\n"
        # A REPL without an `interface`, like a `BasicREPL`, exists while Julia still runs its hooks: wait for the
        # backend, which Julia starts after them.
        Core.eval(Base, :(active_repl = $(FakeREPL())))
        Core.eval(Base, :(is_interactive = true))
        try
            waiting = Threads.@spawn StartupPackage.wait_for_repl()
            sleep(0.2)
            @test !istaskdone(waiting)
            Core.eval(Base, :(active_repl_backend = :backend))
            @test timedwait(() -> istaskdone(waiting), 5) === :ok
            # An interactive session may have no REPL, so waiting ends after the limit.
            Core.eval(Base, :(active_repl_backend = nothing))
            @test 0.3 <= @elapsed(StartupPackage.wait_for_repl(0.3)) < 5
        finally
            Core.eval(Base, :(is_interactive = false))
            Core.eval(Base, :(active_repl_backend = nothing))
        end
    end

    @testset "startup errors" begin
        output = tempname()
        for keys in (0, 1)
            mistate = FakeLineEdit.MIState(keys, Channel{Function}(), Symbol[])
            Core.eval(Base, :(active_repl = $(EditREPL(mistate))))
            Core.eval(Base, :(active_repl_backend = $(FakeBackend(Any[]))))
            at_prompt = Ref("")
            try
                open(output, "w") do io
                    redirect_stderr(io) do
                        StartupPackage.report("failed")
                        # As the REPL runs it while it waits for input, and then the transforms of each input.
                        take!(mistate.async_channel)(mistate)
                        flush(io)
                        at_prompt[] = read(output, String)
                        foreach(transform -> transform(:(1 + 1)), Base.active_repl_backend.ast_transforms)
                    end
                end
            finally
                Core.eval(Base, :(active_repl = $(FakeREPL())))
                Core.eval(Base, :(active_repl_backend = nothing))
            end
            # Shown at once only if nothing was typed, and only once.
            @test (at_prompt[], read(output, String), mistate.calls) ==
                (keys == 0 ? ("failed\n", "failed\n", [:clear, :refresh]) : ("", "failed\n", Symbol[]))
        end
    end

    @testset "generated package" begin
        mktempdir() do depot
            config = mkpath(joinpath(depot, "config"))
            file = joinpath(config, "startup.jl")
            write(file, """
                using StartupPackage
                @startup name = "StartupPackageTest" begin
                    using Printf: @sprintf
                    formatted(x) = @sprintf("%.1f", x)
                    atreplinit() do repl end
                    session = "ran"
                    autoloads = [:(using Statistics: mean)]
                    let T = Int
                        global typed_session::T = 1
                    end
                end
                """)
            pushfirst!(DEPOT_PATH, depot)
            # `Pkg.test` leaves the standard libraries off `LOAD_PATH`.
            "@stdlib" in LOAD_PATH || push!(LOAD_PATH, "@stdlib")
            checked = joinpath(config, "StartupPackageTest", "checked-v$(VERSION.major).$(VERSION.minor)")
            stub = joinpath(config, "StartupPackageTest", "src", "StartupPackageTest.jl")
            replacement = joinpath(config, "replacement.jl")
            failing = joinpath(config, "failing.jl")
            write(failing, "using StartupPackage\n@startup begin\n    error(\"boom\")\nend\n")
            output = joinpath(config, "stderr.txt")
            # The log messages of the background task go to the logger of the task that starts it.
            in_background(name, file) = Test.collect_test_logs(min_level = Base.CoreLogging.Info) do
                open(output, "w") do io
                    redirect_stderr(io) do
                        StartupPackage.load(name, file, Pair{String, String}[], ["Printf"], true)
                        wait(StartupPackage.LOADING[]::Task)
                    end
                end
            end[1]
            try
                @test isempty(in_background("StartupPackageTest", file))
                @test read(output, String) == "`StartupPackageTest` is precompiled in the background.\n"
                cp(file, replacement)
                touch(checked)
                StartupPackage.load("StartupPackageTest", replacement, Pair{String, String}[], ["Printf"])
                @test isempty(in_background("StartupPackageFailing", failing))
                @test occursin(r"^`StartupPackageFailing` is precompiled.*Loading `StartupPackageFailing` failed: .*boom"s,
                    read(output, String))
                # Hooks registered while loading run after a cold precompilation, which leaves the
                # precompilation buffer unwritable on Julia 1.10.
                hooking = joinpath(config, "hooking.jl")
                write(hooking, """
                    using StartupPackage
                    @startup begin
                        atreplinit(repl -> push!(Main.hook_calls, repl))
                        atreplinit(repl -> error("hook broken"))
                    end
                    """)
                Core.eval(Main, :(hook_calls = Any[]))
                Core.eval(Base, :(active_repl = $(FakeREPL())))
                @test isempty(in_background("StartupPackageHooks", hooking))
                @test latest(Main, :hook_calls) == [FakeREPL()]
                @test occursin("A REPL hook of `StartupPackageHooks` failed: hook broken", read(output, String))
                @test StartupPackage.guard_imports in Base.repl_hooks
            finally
                popfirst!(DEPOT_PATH)
            end
            mod = latest(Main, :StartupPackageTest)
            @test Base.PkgId(mod) == Base.PkgId(nothing, "StartupPackageTest")
            @test Base.invokelatest(latest(Main, :formatted), 1) == "1.0"
            @test latest(Main, :session) == "ran"
            @test latest(Main, :autoloads) == [:(using Statistics: mean)]
            @test !any(id -> id.name == "Statistics", keys(Base.loaded_modules))
            @test latest(Main, :typed_session) === 1 && Core.get_binding_type(mod, :typed_session) === Int
            @test any(hook -> parentmodule(hook) === mod, Base.repl_hooks)
            @test occursin(repr(replacement), read(stub, String)) && startswith(read(checked, String), replacement)
            @test !isfile(joinpath(config, "StartupPackageTest", "Project.toml"))
        end
    end

